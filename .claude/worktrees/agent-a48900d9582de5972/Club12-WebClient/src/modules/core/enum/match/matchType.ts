/**
 * The types of matches that can exist (Regular or Playoff).
 * @enum MatchType
 */
export enum MatchType {
  /**
   * A regular match in the tournament.
   * @type {string}
   */
  Regular = 'Regular',

  /**
   * A playoff match in the tournament.
   * @type {string}
   */
  Playoff = 'Playoff',
}
